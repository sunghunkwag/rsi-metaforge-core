"""Write the manifests of the kinds made from PMLB, from the collection's own summary table.

    python rsi6/results/design_t_20261124/scripts/make_manifests.py SUMMARY_TSV kind [kind ...]

``SUMMARY_TSV`` is ``pmlb/all_summary_stats.tsv`` of the PMLB repository (its SHA-256 is written
into every manifest). A kind is a rule over that table: task, number of rows, number of
attributes and the data set's name. No data set is opened here and no learner is involved.
"""
import csv
import hashlib
import json
import os
import sys

BASE = "https://media.githubusercontent.com/media/EpistasisLab/pmlb/master/datasets/{0}/{0}.tsv.gz"
TWINS = {"573_cpu_act", "562_cpu_small", "mushroom"}                # the same table under a second name (197_cpu_act, 227_cpu_small, agaricus_lepiota)
MADE = ("GAMETES", "parity5", "mux6", "threeOf9", "xd6", "monk", "corral", "mofn", "tic_tac_toe", "banana", "ring", "twonorm",
        "prnn_synth", "Hill_Valley", "led", "waveform")              # generated by a written rule or a simulator, by name


def plain(r):
    return not r["dataset"].startswith(("_deprecated", "feynman", "strogatz", "first_principles")) and r["dataset"] not in TWINS


RULES = {
    "friedman": ("regression data sets of the Friedman generator (name contains '_fri_c', or is 564_fried) with at least "
                 "100 rows and at most 25 attributes",
                 lambda r: r["task"] == "regression" and ("_fri_c" in r["dataset"] or r["dataset"] == "564_fried")
                 and int(r["n_instances"]) >= 100 and int(r["n_features"]) <= 25),
    "table": ("regression data sets other than the Feynman, Strogatz, Friedman, first-principles and BNG families, the poker "
              "table, deprecated names and second names of one table, with at least 100 rows and at most 25 attributes",
              lambda r: r["task"] == "regression" and plain(r) and "_fri_c" not in r["dataset"] and r["dataset"] != "564_fried"
              and "BNG" not in r["dataset"] and r["dataset"] != "1595_poker"
              and int(r["n_instances"]) >= 100 and int(r["n_features"]) <= 25),
    "binary": ("classification data sets with two classes, not generated by a written rule or a simulator (by name), not "
               "deprecated and not a second name of one table, with at least 100 rows and at most 25 attributes",
               lambda r: r["task"] == "classification" and float(r["n_classes"]) == 2 and plain(r)
               and not r["dataset"].startswith(MADE) and int(r["n_instances"]) >= 100 and int(r["n_features"]) <= 25),
    "classes": ("classification data sets with more than two classes, not generated by a written rule or a simulator (by "
                "name), not deprecated, with at least 100 rows and at most 25 attributes, and not the poker table",
                lambda r: r["task"] == "classification" and float(r["n_classes"]) > 2 and plain(r)
                and not r["dataset"].startswith(MADE) and r["dataset"] != "poker"
                and int(r["n_instances"]) >= 100 and int(r["n_features"]) <= 25),
    "made": ("classification data sets with two classes that were generated by a written rule or a simulator (by name: "
             + ", ".join(MADE) + "), not deprecated, with at least 100 rows and at most 25 attributes",
             lambda r: r["task"] == "classification" and float(r["n_classes"]) == 2 and plain(r)
             and r["dataset"].startswith(MADE) and int(r["n_instances"]) >= 100 and int(r["n_features"]) <= 25),
    "flows": ("regression data sets of the Strogatz family (the rate of change of a two-variable dynamical system)",
              lambda r: r["task"] == "regression" and r["dataset"].startswith("strogatz")),
}


def main():
    summary, kinds = sys.argv[1], sys.argv[2:]
    sha = hashlib.sha256(open(summary, "rb").read()).hexdigest()
    rows = list(csv.DictReader(open(summary), delimiter="\t"))
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.abspath(os.path.join(here, "..", "..", "..", "environments", "manifests"))
    for kind in kinds:
        text, rule = RULES[kind]
        chosen = sorted((r for r in rows if rule(r)), key=lambda r: r["dataset"])
        manifest = {"name": kind, "category": kind,
                    "source": "Penn Machine Learning Benchmarks (github.com/EpistasisLab/pmlb), the data set tables as published",
                    "terms": "MIT licence (the repository's LICENSE). Fetched by hash, not committed.",
                    "reference": "the target column of the rows used as queries (kernel only)",
                    "rule": text, "summary_table_sha256": sha,
                    "files": [{"url": BASE.format(r["dataset"]), "path": r["dataset"] + ".tsv.gz", "sha256": None,
                               "rows": int(r["n_instances"]), "features": int(r["n_features"])} for r in chosen]}
        path = os.path.join(out, kind + ".json")
        if os.path.exists(path):                                    # keep hashes that a fetch has recorded
            old = {e["path"]: e.get("sha256") for e in json.load(open(path))["files"]}
            for e in manifest["files"]:
                e["sha256"] = old.get(e["path"])
        json.dump(manifest, open(path, "w"), indent=1)
        print(kind, len(chosen), "data sets")


if __name__ == "__main__":
    main()
